package com.focusgate.app.util

import kotlin.random.Random

/**
 * 深刻问题库 —— 每次随机选取，打破用户心理惯性
 *
 * 按干预场景分组，每个问题都旨在：
 * - 打断无意识刷屏的「自动驾驶」状态
 * - 唤起对时间、注意力、生命质量的真实感知
 * - 让用户对自己诚实，而非说教
 */
object DeepQuestionBank {

    /** ======================== 中途提醒（5 分钟 / 70% 节点） ======================== */
    val midwayQuestions: List<String> = listOf(
        "你记得过去五分钟里，刷到了什么让你印象深刻的内容吗？",
        "你现在是真正的放松，还是只是在麻木地滑动？",
        "如果现在关掉手机，你会有一种「失去了什么」的感觉吗？",
        "你刷短视频的时候，大脑是更清醒了，还是更混沌了？",
        "你注意一下自己的呼吸 —— 现在是深还是浅？",
        "刚才这几分钟里，有哪一个画面是你愿意主动记住的？",
        "你是在「休息」，还是在「逃离」？",
        "你的眼睛现在是什么感觉？试试把视线从屏幕上移开三秒。",
        "如果用一个词形容你现在的心理状态，你会选哪个词？",
        "你上一次因为刷到某个视频而真正改变了一个想法，是什么时候？",
        "你现在的身体姿势是怎样的？是松弛的还是紧张的？",
        "你是在消费别人创造的内容，还是在浪费自己的时间？",
        "你现在做的事，和你十分钟前想做的事，是同一件吗？",
        "你觉得自己是在「主动选择」，还是被算法「推着走」？",
        "你刷视频时能随时停下来吗？还是说「再看一个」就停不下来了？"
    )

    /** ======================== 超时中断（最终拦截） ======================== */
    val timeoutQuestions: List<String> = listOf(
        "计划时间已经到了。你真的需要「再刷五分钟」，还是只是不想面对接下来要做的事？",
        "如果你把刚才花在这上面的时间，用来做一件你一直拖延的事，现在会怎样？",
        "一小时后回想此刻，你会庆幸自己停下了，还是后悔没多刷一会儿？",
        "你今天的计划里，原本打算用这段时间做什么？",
        "你觉得刚才这段时间，是「属于自己的时间」，还是「被偷走的时间」？",
        "如果这是你生命中最后一小时，你还会把它花在这里吗？",
        "你打开这个 App 之前想解决的问题（累/烦/无聊），现在解决了吗？",
        "你是在用短视频「填充时间」，还是在用「别人的生活」逃避自己的生活？",
        "你上一次放下手机后感到充实和满足，是做了什么？",
        "你注意过没有 —— 刷完以后的空虚感和刷之前的渴望，哪个更强烈？",
        "这些内容是在「滋养」你，还是在「消耗」你？",
        "如果你现在停下来，你最需要面对的是什么？",
        "对你的未来而言，此刻的选择重要吗？",
        "你是不是已经忘记了「无聊」也可以是一种很好的状态？",
        "你真正渴望的，是屏幕里的内容，还是屏幕外的某种生活？",
        "你有没有发现：你打开它是因为「想刷」，而不是因为「需要刷」？",
        "时间是你最稀缺的资源 —— 你确定要这样花掉它吗？",
        "你是在用刷手机「奖励」自己，还是在用「消耗」替代真正的休息？",
        "你记得你打开前选的是几分钟吗？现在时间到了。",
        "这件事对你今天剩下的时间有什么影响？"
    )

    /** ======================== 二次确认页（连续无意识打开） ======================== */
    val doubleConfirmQuestions: List<String> = listOf(
        "你今天已经连续多次无意识地打开它了。你真的想打开，还是只是手指的条件反射？",
        "同样的动作反复做，却期待不同的结果 —— 你觉得这次会不一样吗？",
        "你还记得第一次打开时是为了什么吗？现在还在做那件事吗？",
        "如果有一个朋友也像你这样反复打开又后悔，你会对他说什么？",
        "你是在「选择」打开，还是在被「习惯」支配？",
        "你今天的精力余额已经用掉不少了 —— 你确定要再消耗一笔吗？"
    )

    /** ======================== 悬浮覆盖层（超时后） ======================== */
    val overlayQuestions: List<String> = listOf(
        "你已经超出计划时间了。每次都说「再看一个」，但真的有最后一个吗？",
        "你的注意力已经被算法卖了多少次了？",
        "你还要继续假装「看完这个就停」吗？",
        "你的大脑已经发出疲劳信号了 —— 你听到了吗？",
        "你想成为自己时间的主人，还是别人流量的贡献者？"
    )

    /** ======================== 随机器 ======================== */
    private val usedKeys = mutableSetOf<Int>()

    /** 从中途提醒问题池随机选一个 */
    fun randomMidway(): String = pick(midwayQuestions)

    /** 从超时问题池随机选一个 */
    fun randomTimeout(): String = pick(timeoutQuestions)

    /** 从二次确认问题池随机选一个 */
    fun randomDoubleConfirm(): String = pick(doubleConfirmQuestions)

    /** 从悬浮层问题池随机选一个 */
    fun randomOverlay(): String = pick(overlayQuestions)

    /** 从所有问题中随机选一个（不分组） */
    fun randomAny(): String {
        val all = midwayQuestions + timeoutQuestions + doubleConfirmQuestions + overlayQuestions
        return pick(all)
    }

    /** 避免连续两次重复的随机选取 */
    @Synchronized
    private fun pick(pool: List<String>): String {
        if (pool.isEmpty()) return ""
        // 如果可用的非重复项不够，重置
        if (usedKeys.size >= pool.size) usedKeys.clear()

        val available = pool.filterIndexed { index, _ -> index !in usedKeys }
        val chosen = available[Random.nextInt(available.size)]
        usedKeys.add(pool.indexOf(chosen))
        return chosen
    }

    /** 重置使用记录（新会话时调用） */
    @Synchronized
    fun resetTracking() {
        usedKeys.clear()
    }
}
